package worksheet06;

public class Exercise03 {

	// Das Beispiel starten und die vorbereiteten Eingaben bzw. Ausgaben ausführen.
	public static void main(String[] args) {
		int n = 4;
		for (int i = 1; i<=n ; i++) {
			for ( int j = 1; j <= i; j++) {
				System.out.print("*");
			}
			System.out.println();
		}

	}

}
